################################################################################
# Main Execution
################################################################################

main() {
  log_section "AWS Amplify Discovery Script"

  # Pre-flight checks
  check_dependencies
  check_aws_credentials

  # Display configuration
  if [ -n "$AWS_PROFILE" ]; then
    log_info "Profile: $AWS_PROFILE"
  fi
  log_info "Region: $REGION"
  log_info "Account: $($AWS_CMD sts get-caller-identity --query Account --output text)"

  # Create output directory
  mkdir -p "$OUTPUT_DIR"
  log_info "Output directory: $OUTPUT_DIR"

  # Initialize output files
  local md_file="$OUTPUT_DIR/DISCOVERY-REPORT.md"
  local csv_file="$OUTPUT_DIR/amplify-inventory.csv"

  init_markdown "$md_file"
  init_csv "$csv_file"

  # Discover apps
  log_section "Discovering Amplify Apps"
  local app_ids=$(discover_amplify_apps)

  if [ -z "$app_ids" ]; then
    log_warn "No Amplify apps found in region $REGION"
    echo "No applications found in region $REGION" >>"$md_file"
    exit 0
  fi

  local app_count=$(echo "$app_ids" | wc -l | tr -d ' ')
  log_info "Found $app_count Amplify app(s)"

  # Save raw apps list
  $AWS_CMD amplify list-apps --region "$REGION" >"$OUTPUT_DIR/apps-raw.json"

  # Summary section
  cat >>"$md_file" <<EOF
**Total Applications:** $app_count  
**Discovery Date:** $TIMESTAMP

EOF

  echo "" >>"$md_file"
  echo "## Applications" >>"$md_file"

  # Process each app
  local app_number=1
  for app_id in $app_ids; do
    log_section "Processing App $app_number/$app_count: $app_id"

    # Get app details
    log_info "Fetching app details..."
    local app_json=$(get_app_details "$app_id")
    echo "$app_json" >"$OUTPUT_DIR/app-${app_id}.json"

    local app_name=$(echo "$app_json" | jq -r '.app.name')
    local repo=$(echo "$app_json" | jq -r '.app.repository // "N/A"')
    local platform=$(echo "$app_json" | jq -r '.app.platform // "WEB"')
    local iam_role=$(echo "$app_json" | jq -r '.app.iamServiceRoleArn // "N/A"')
    local created=$(echo "$app_json" | jq -r '.app.createTime')
    local updated=$(echo "$app_json" | jq -r '.app.updateTime')

    log_info "App Name: $app_name"

    # Generate markdown for app
    generate_markdown_app "$app_json" "$md_file"

    # CSV row for app
    generate_csv_row "App" "$app_id" "$app_name" "" "" "$repo" "$platform" "" "" "$iam_role" "$created" "$updated" ""

    # Get branches
    log_info "Fetching branches..."
    local branches_json=$(get_branches "$app_id")
    echo "$branches_json" >"$OUTPUT_DIR/app-${app_id}-branches.json"
    generate_markdown_branches "$app_id" "$app_name" "$branches_json" "$md_file"

    # CSV rows for branches
    echo "$branches_json" | jq -r '.branches[] | @json' | while read -r branch; do
      local branch_name=$(echo "$branch" | jq -r '.branchName')
      local framework=$(echo "$branch" | jq -r '.framework // "N/A"')
      local stage=$(echo "$branch" | jq -r '.stage')
      local branch_updated=$(echo "$branch" | jq -r '.updateTime')

      generate_csv_row "Branch" "$app_id" "$app_name" "$branch_name" "" "" "" "$framework" "$stage" "" "" "$branch_updated" ""
    done

    # Get domains
    log_info "Fetching domains..."
    local domains_json=$(get_domains "$app_id")
    echo "$domains_json" >"$OUTPUT_DIR/app-${app_id}-domains.json"
    generate_markdown_domains "$domains_json" "$md_file"

    # CSV rows for domains
    echo "$domains_json" | jq -r '.domainAssociations[]? | @json' 2>/dev/null | while read -r domain; do
      local domain_name=$(echo "$domain" | jq -r '.domainName')
      local domain_status=$(echo "$domain" | jq -r '.domainStatus')

      generate_csv_row "Domain" "$app_id" "$app_name" "" "$domain_name" "" "" "" "" "" "" "" "$domain_status"
    done

    # Get webhooks
    log_info "Fetching webhooks..."
    local webhooks_json=$(get_webhooks "$app_id")
    echo "$webhooks_json" >"$OUTPUT_DIR/app-${app_id}-webhooks.json"

    local webhook_count=$(echo "$webhooks_json" | jq -r '.webhooks | length')
    if [ "$webhook_count" -gt 0 ]; then
      echo "" >>"$md_file"
      echo "#### Webhooks" >>"$md_file"
      echo "" >>"$md_file"
      echo '```json' >>"$md_file"
      echo "$webhooks_json" | jq '.webhooks' >>"$md_file"
      echo '```' >>"$md_file"

      log_warn "App has $webhook_count webhook(s) - review before import"
    fi

    # Get backend environments
    log_info "Fetching backend environments..."
    local backends_json=$(get_backend_environments "$app_id")
    echo "$backends_json" >"$OUTPUT_DIR/app-${app_id}-backends.json"

    local backend_count=$(echo "$backends_json" | jq -r '.backendEnvironments | length')
    if [ "$backend_count" -gt 0 ]; then
      echo "" >>"$md_file"
      echo "#### Backend Environments" >>"$md_file"
      echo "" >>"$md_file"
      echo '```json' >>"$md_file"
      echo "$backends_json" | jq '.backendEnvironments' >>"$md_file"
      echo '```' >>"$md_file"

      log_warn "App has $backend_count backend environment(s) - may need additional Terraform resources"
    fi

    echo "" >>"$md_file"
    echo "---" >>"$md_file"

    ((app_number++))
  done

  # Generate import commands
  log_section "Generating Import Commands"
  generate_import_commands "$md_file"

  # Generate next steps
  log_section "Generating Next Steps"
  generate_next_steps "$md_file"

  # Summary
  log_section "Discovery Complete!"
  echo ""
  log_info "📄 Files generated:"
  log_info "   - $md_file (Main report)"
  log_info "   - $csv_file (Inventory spreadsheet)"
  log_info "   - $OUTPUT_DIR/*.json (Raw API responses)"
  log_info "   - $OUTPUT_DIR/*-amplify.yml (Build specifications)"
  echo ""
  log_info "🎯 Next: Review the markdown report and start Terraform migration"
  echo ""

  # Open markdown file if possible
  if command -v open &>/dev/null; then
    log_info "Opening report..."
    open "$md_file" 2>/dev/null || true
  elif command -v xdg-open &>/dev/null; then
    xdg-open "$md_file" 2>/dev/null || true
  fi
}

# Run main function
main "$@"
